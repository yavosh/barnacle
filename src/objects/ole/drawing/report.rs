fn formula(data: &[u8], out: &mut Report) -> io::Result<()> {
    let Some(header) = data.get(..22) else {
        out.unknown(0, 128);
        return Ok(());
    };
    let number = |at: usize| u16::from_le_bytes([header[at], header[at + 1]]);
    let mut tokens = &data[22..];
    let len = number(20);
    write!(
        out,
        " - R{}C{} len={} ",
        u32::from(number(0)) + 1,
        u32::from(number(2)) + 1,
        len
    )?;
    if tokens.len() != usize::from(len) {
        out.unknown(0, 128 + tokens.len() as u64 * 1024);
        return Ok(());
    }
    while let Some((&code, rest)) = tokens.split_first() {
        let label = match code {
            0x03 => "ptgAdd",
            0x04 => "ptgSub",
            0x05 => "ptgMul",
            0x06 => "ptgDiv",
            0x08 => "ptgConcat",
            0x09 => "ptgLt",
            0x0a => "ptgLe",
            0x0b => "ptgEq",
            0x0c => "ptgGe",
            0x0d => "ptgGt",
            0x0e => "ptgNe",
            0x1d if !rest.is_empty() => "ptgBool",
            0x1e if rest.len() >= 2 => "ptgInt",
            0x1f if rest.len() >= 8 => "ptgNum",
            0x24 if rest.len() >= 4 => "ptgRef",
            0x44 if rest.len() >= 4 => "ptgRefV",
            0x25 if rest.len() >= 8 => "ptgArea",
            0x19 if rest.starts_with(&[0x10, 0, 0]) => "ptgAttr",
            0x41 if rest.starts_with(&[20, 0]) => "ptgFuncV",
            0x42 if rest.get(1..3) == Some(&[4, 0]) => "ptgFuncVarV",
            _ => {
                out.unknown(0, 128 + tokens.len() as u64 * 1024);
                return Ok(());
            }
        };
        write!(out, " {label}")?;
        let used = match code {
            0x1d => {
                write!(out, " {}", if rest[0] == 0 { "FALSE" } else { "TRUE" })?;
                1
            }
            0x1e => {
                write!(out, " {}", u16::from_le_bytes([rest[0], rest[1]]))?;
                2
            }
            0x1f => {
                let v = f64::from_le_bytes(rest[..8].try_into().unwrap());
                if v.is_finite() {
                    write!(out, " {v:.6}")?;
                } else {
                    out.unknown(3, 12);
                }
                8
            }
            0x24 | 0x44 => {
                let row = u16::from_le_bytes([rest[0], rest[1]]);
                let col = u16::from_le_bytes([rest[2], rest[3]]);
                if row < 0x4000 {
                    write!(out, " R{}C{}", u32::from(row) + 1, u32::from(col) + 1)?;
                } else {
                    out.unknown(5, 20);
                }
                4
            }
            0x41 => {
                out.write_all(b" SQRT (0x0014)")?;
                2
            }
            0x42 => {
                write!(out, " args {} func SUM (0x0004)", rest[0])?;
                3
            }
            0x25 => {
                let word = |i| u16::from_le_bytes([rest[i], rest[i + 1]]);
                if word(0) < 0x4000 && word(4) < 0x4000 {
                    write!(
                        out,
                        " R{}C{}:R{}C{}",
                        u32::from(word(0)) + 1,
                        u32::from(word(2)) + 1,
                        u32::from(word(4)) + 1,
                        u32::from(word(6)) + 1
                    )?;
                } else {
                    out.unknown(10, 40);
                }
                8
            }
            0x19 => 3,
            _ => 0,
        };
        tokens = &rest[used..];
    }
    // The final observed formatter token does not belong to the formula's Rgce token sequence.
    // Later report hashes are eligible only if every flushed byte precedes this uncertain suffix.
    out.unknown(0, 64);
    Ok(())
}

pub(super) fn scan(
    input: &mut Input<'_>,
    sink: &mut dyn ChildSink,
    retain: bool,
) -> io::Result<Handling> {
    input.seek(SeekFrom::Start(0))?;
    let mut remaining = input.len();
    let mut buf = [0; MAX_RECORD];
    let mut out = Report::new(sink, retain)?;
    while remaining >= 4 {
        sink.check()?;
        let mut header = [0; 4];
        input.read_exact(&mut header)?;
        let code = u16::from_le_bytes([header[0], header[1]]);
        let n = u16::from_le_bytes([header[2], header[3]]) as usize;
        if n > MAX_RECORD || n as u64 > remaining - 4 {
            return Ok(Handling::Incomplete);
        }
        remaining -= 4 + n as u64;
        if matches!(code, 6 | 0x85) {
            input.read_exact(&mut buf[..n])?;
        } else {
            input.seek(SeekFrom::Current(n as i64))?;
        }
        let Some(label) = label(code) else {
            let upper = match code {
                0x18 | 0x207 => 128 + n as u64 * 4,
                _ => 74,
            };
            out.unknown(15, upper);
            continue;
        };
        write!(out, "{code:04x} {n:6}   {label}")?;
        match code {
            0x0006 => formula(&buf[..n], &mut out)?,
            0x0085 if n >= 6 => {
                let kind = match buf[5] {
                    0 => Some("worksheet or dialog sheet"),
                    2 => Some("chart"),
                    _ => None,
                };
                let state = match buf[4] {
                    0 => Some("visible"),
                    1 => Some("hidden"),
                    2 => Some("very hidden"),
                    _ => None,
                };
                if let (Some(kind), Some(state)) = (kind, state) {
                    write!(out, " - {kind}, {state}")?;
                } else {
                    out.unknown(10, 56);
                }
            }
            _ => {}
        }
        out.write_all(b"\n")?;
    }
    out.finish(input, sink)
}
