//! The Debian BIFF report includes the preamble and complete flushed record-text blocks.
use super::{ChildSink, Handling, Input, MAX_RECORD, REPORT_HEADER};
use crate::objects::Snapshot;
use std::io::{self, BufWriter, Read, Seek, SeekFrom, Write};

const BLOCK: u64 = 4096;

struct Report {
    spool: Option<BufWriter<Snapshot>>,
    payload_budget: u64,
    minimum: u64,
    maximum: u64,
    first_unknown: Option<u64>,
}

impl Report {
    fn new(sink: &mut dyn ChildSink, retain: bool) -> io::Result<Self> {
        let mut spool = retain.then(|| BufWriter::new(Snapshot::new(sink.temporary_directory())));
        if let Some(file) = &mut spool {
            file.write_all(REPORT_HEADER)?;
        }
        Ok(Self {
            spool,
            payload_budget: sink.remaining().saturating_sub(REPORT_HEADER.len() as u64),
            minimum: 0,
            maximum: 0,
            first_unknown: None,
        })
    }
    fn unknown(&mut self, min: u64, max: u64) {
        self.first_unknown.get_or_insert(self.minimum);
        self.minimum = self.minimum.saturating_add(min);
        self.maximum = self.maximum.saturating_add(max);
    }
    fn finish(mut self, input: &mut Input<'_>, sink: &mut dyn ChildSink) -> io::Result<Handling> {
        // A full last block still belongs to stdio until a further byte is written.
        let flushed = |size: u64| size.saturating_sub(1) / BLOCK * BLOCK;
        let low = flushed(self.minimum);
        let high = flushed(self.maximum);
        let total = |bytes: u64| bytes.saturating_add(REPORT_HEADER.len() as u64);
        if sink.child_limit().is_some() && total(high) <= sink.remaining() {
            sink.can_enter_child();
            return Ok(Handling::Complete);
        }
        if low != high {
            // An interval between two sizes rejected for the same reason has a known outcome.
            let reason = sink.size_limit(total(low));
            if reason.is_some() && reason == sink.size_limit(total(high)) {
                sink.skip_declared_size(total(low));
                return Ok(Handling::Complete);
            }
            return Ok(Handling::Incomplete);
        }
        if sink.skip_declared_size(total(low)) || !sink.can_enter_child() {
            return Ok(Handling::Complete);
        }
        if self.first_unknown.is_some_and(|known| known < low) {
            return Ok(Handling::Incomplete);
        }
        let Some(mut file) = self.spool.take() else {
            // Sizing established that the report fits. Re-read only when the estimate required it.
            return scan(input, sink, true);
        };
        file.flush()?;
        let file = file.into_inner().map_err(io::IntoInnerError::into_error)?;
        let size = usize::try_from(total(low)).map_err(io::Error::other)?;
        file.with_bytes(|bytes| {
            Ok(if sink.match_generic_view(&bytes[..size])? {
                Handling::Stopped
            } else {
                Handling::Complete
            })
        })
    }
}

impl Write for Report {
    fn write(&mut self, buf: &[u8]) -> io::Result<usize> {
        if self.first_unknown.is_none()
            && self.minimum < self.payload_budget
            && let Some(file) = &mut self.spool
        {
            let keep = (self.payload_budget - self.minimum).min(buf.len() as u64) as usize;
            file.write_all(&buf[..keep])?;
        }
        self.minimum = self.minimum.saturating_add(buf.len() as u64);
        self.maximum = self.maximum.saturating_add(buf.len() as u64);
        Ok(buf.len())
    }
    fn flush(&mut self) -> io::Result<()> {
        if let Some(file) = &mut self.spool {
            file.flush()?;
        }
        Ok(())
    }
}

